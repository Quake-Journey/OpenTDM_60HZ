"""The parity harness for the ORIGINAL OpenTDM tree (the reference module).

The full harness does not compile against the original tree (its scenarios
read fields the port added). This writes a reduced harness source: harness.c
with only the rocket jump scenario, the parity scenarios, their usercmd
stream and the match helpers, cut byte for byte out of scenarios_60hz.h and
scenarios.h (the same code runs against both trees). Output:
<out>/harness_rj.c and <out>/scenarios_rj.h; build with
build_harness_win.py --harness-src <out>/harness_rj.c.

usage: python make_rj_orig.py --out DIR [--api3 DIR]
"""
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
API3 = HERE.parents[1] / 'tests' / 'tickrate-tests' / 'mods' / 'api3'


def cut(text, start, end):
    a = text.index(start)
    b = text.index(end, a)
    return text[a:b]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--api3', default=str(API3))
    a = ap.parse_args(argv)
    api3 = Path(a.api3)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    harness = (api3 / 'harness.c').read_text(encoding='ascii')
    sc = (api3 / 'scenarios.h').read_text(encoding='ascii')
    sc60 = (api3 / 'scenarios_60hz.h').read_text(encoding='ascii')

    parts = [
        '/* generated by make_rj_orig.py: the rocket jump scenario only */\n',
        cut(sc, 'static void h_real_phase(int k)', 'static void h_hit('),
        cut(sc, '/* two players in the two teams', '/* announcements "N'),
        cut(sc60, 'static const int f_msec[6]', 'enum { F_NONE'),
        cut(sc60, '/* opentdm-60hz, PO local test 17.11', '#define H_SCENARIOS_F'),
        '#include "scenarios_parity.h"\n',
        'static const struct { const char *name; void (*run)(void); } h_scenarios[] = {\n'
        '    { "f_rocket_jump", sc_f_rocket_jump },\n    H_SCENARIOS_PARITY\n    { NULL, NULL }\n};\n',
    ]
    (out / 'scenarios_rj.h').write_text(''.join(parts), encoding='ascii', newline='\n')

    assert harness.count('#include "scenarios.h"\n') == 1
    assert harness.count('static void h_start(const char *entities)\n') == 1
    harness = harness.replace('#include "scenarios.h"\n', '#include "scenarios_rj.h"\n')
    # the original tree has no variable FPS handshake; at 10 Hz h_start does not use it
    harness = harness.replace('static void h_start(const char *entities)\n',
                              '#ifndef GMF_VARIABLE_FPS\n#define GMF_VARIABLE_FPS 0\n#endif\n'
                              'static void h_start(const char *entities)\n')
    # the generated file is compiled outside api3: its quoted includes must find the api3 headers
    (out / 'harness_rj.c').write_text(harness, encoding='ascii', newline='\n')
    for f in ('harness_rj.c', 'scenarios_rj.h'):
        t = (out / f).read_text(encoding='ascii')
        assert all(ord(c) >= 32 or c in '\n\t' for c in t), f
    print(out / 'harness_rj.c')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
